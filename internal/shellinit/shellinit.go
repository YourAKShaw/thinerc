// Package shellinit emits the tiny, static shell glue that `eval "$(thine init
// zsh)"` loads: guarded one-line functions that call the binary. No hooks, no
// prompt code, nothing that runs per command (ADR-0002).
package shellinit

import (
	"fmt"
	"sort"
	"strings"

	"github.com/YourAKShaw/thinerc/internal/config"
)

// Shells lists supported shells.
var Shells = []string{"bash", "zsh", "fish"}

// Shortcut is one shell function that forwards to `thine <args…>`.
type Shortcut struct {
	Name  string
	Args  []string
	Desc  string
	Force bool
}

var builtin = []Shortcut{
	{Name: "whoport", Args: []string{"port"}, Desc: "Who is listening on a port"},
	{Name: "ports", Args: []string{"ports"}, Desc: "List your listening dev ports"},
	{Name: "kp", Args: []string{"kill"}, Desc: "Gracefully free a port"},
	{Name: "killport", Args: []string{"kill"}, Desc: "Gracefully free a port"},
	{Name: "freeup", Args: []string{"freeup"}, Desc: "Honest memory report and reclaim"},
	{Name: "cleanup", Args: []string{"cleanup"}, Desc: "Plan, apply and undo disk cleanup"},
	{Name: "whatsup", Args: []string{"whatsup"}, Desc: "One-screen system dashboard"},
	{Name: "nuke-nm", Args: []string{"nm", "reset"}, Desc: "Reinstall node_modules with rollback"},
}

// Build returns the final shortcut list from config: built-ins, group
// aliases and recipe aliases, minus disabled names, with renames applied.
func Build(c *config.Config) []Shortcut {
	var out []Shortcut
	out = append(out, builtin...)
	groups := make([]string, 0, len(c.Groups))
	for g := range c.Groups {
		groups = append(groups, g)
	}
	sort.Strings(groups)
	for _, g := range groups {
		if a := c.Groups[g].Alias; a != "" {
			out = append(out, Shortcut{Name: a, Args: []string{"kill", "--group", g}, Desc: "Free the " + g + " port group"})
		}
	}
	recipes := make([]string, 0, len(c.Recipes))
	for r := range c.Recipes {
		recipes = append(recipes, r)
	}
	sort.Strings(recipes)
	for _, r := range recipes {
		if a := c.Recipes[r].Alias; a != "" {
			out = append(out, Shortcut{Name: a, Args: []string{"run", r, "--"}, Desc: firstNonEmpty(c.Recipes[r].Description, "Run recipe "+r)})
		}
	}
	disabled := map[string]bool{}
	for _, d := range c.Shortcuts.Disable {
		disabled[d] = true
	}
	force := map[string]bool{}
	for _, f := range c.Shortcuts.Force {
		force[f] = true
	}
	seen := map[string]bool{}
	var final []Shortcut
	for _, s := range out {
		if disabled[s.Name] {
			continue
		}
		if r, ok := c.Shortcuts.Rename[s.Name]; ok && config.ValidName(r) {
			s.Name = r
		}
		if seen[s.Name] {
			continue
		}
		seen[s.Name] = true
		s.Force = force[s.Name]
		final = append(final, s)
	}
	return final
}

func firstNonEmpty(a, b string) string {
	if a != "" {
		return a
	}
	return b
}

// Quote single-quotes a word for POSIX shells and fish.
func Quote(s string) string {
	if s != "" && strings.IndexFunc(s, func(r rune) bool {
		return !(r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9' || strings.ContainsRune("-_./:=@", r))
	}) < 0 {
		return s
	}
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

func quoteFish(s string) string {
	if Quote(s) == s {
		return s
	}
	return "'" + strings.NewReplacer(`\`, `\\`, `'`, `\'`).Replace(s) + "'"
}

// Options configure generated code.
type Options struct {
	Bin        string // "thine" or an absolute path
	Version    string
	Greeting   bool
	ZshCompDir string
}

// Render produces the init script for shell.
func Render(shell string, shortcuts []Shortcut, o Options) (string, error) {
	switch shell {
	case "zsh":
		return renderPosix("zsh", shortcuts, o), nil
	case "bash":
		return renderPosix("bash", shortcuts, o), nil
	case "fish":
		return renderFish(shortcuts, o), nil
	}
	return "", fmt.Errorf("unsupported shell %q (supported: %s)", shell, strings.Join(Shells, ", "))
}

func renderPosix(shell string, sc []Shortcut, o Options) string {
	var b strings.Builder
	bin := Quote(o.Bin)
	fmt.Fprintf(&b, "# thine init %s — generated by thine %s; regenerate, don't edit\n", shell, o.Version)
	if shell == "zsh" {
		b.WriteString("typeset -gx THINE_SHELL=zsh\n")
		b.WriteString("function __thine_free { ! whence -- \"$1\" >/dev/null 2>&1 }\n")
	} else {
		b.WriteString("THINE_SHELL=bash; export THINE_SHELL\n")
		b.WriteString("function __thine_free { ! type -t \"$1\" >/dev/null 2>&1; }\n")
	}
	end := ""
	if shell == "bash" {
		end = ";"
	}
	for _, s := range sc {
		args := make([]string, len(s.Args))
		for i, a := range s.Args {
			args[i] = Quote(a)
		}
		// The `function` keyword matters: `name() {…}` is alias-expanded at
		// parse time and breaks when the user already has `alias name=…`.
		body := fmt.Sprintf("function %s { command %s %s \"$@\"%s }", s.Name, bin, strings.Join(args, " "), end)
		if s.Force {
			fmt.Fprintf(&b, "unalias %s 2>/dev/null; %s\n", s.Name, body)
		} else {
			fmt.Fprintf(&b, "__thine_free %s && %s\n", s.Name, body)
		}
	}
	if shell == "zsh" {
		b.WriteString("unfunction __thine_free\n")
		if o.ZshCompDir != "" {
			d := Quote(o.ZshCompDir)
			fmt.Fprintf(&b, "if [[ -r %s/_thine ]]; then fpath=(%s $fpath); (( $+functions[compdef] )) && autoload -Uz _thine && compdef _thine thine; fi\n", d, d)
		}
		if o.Greeting {
			fmt.Fprintf(&b, "[[ -o interactive ]] && command %s hello --greeting\n", bin)
		}
	} else {
		b.WriteString("unset -f __thine_free\n")
		if o.Greeting {
			fmt.Fprintf(&b, "[[ $- == *i* ]] && command %s hello --greeting\n", bin)
		}
	}
	return b.String()
}

func renderFish(sc []Shortcut, o Options) string {
	var b strings.Builder
	bin := quoteFish(o.Bin)
	fmt.Fprintf(&b, "# thine init fish — generated by thine %s; regenerate, don't edit\n", o.Version)
	b.WriteString("set -gx THINE_SHELL fish\n")
	b.WriteString("function __thine_free; not type -q -- $argv[1]; end\n")
	for _, s := range sc {
		args := make([]string, len(s.Args))
		for i, a := range s.Args {
			args[i] = quoteFish(a)
		}
		def := fmt.Sprintf("function %s --description %s\n    command %s %s $argv\nend\n",
			s.Name, quoteFish(s.Desc), bin, strings.Join(args, " "))
		if s.Force {
			b.WriteString(def)
		} else {
			fmt.Fprintf(&b, "if __thine_free %s\n%send\n", s.Name, indent(def))
		}
	}
	b.WriteString("functions -e __thine_free\n")
	if o.Greeting {
		fmt.Fprintf(&b, "status is-interactive; and command %s hello --greeting\n", bin)
	}
	return b.String()
}

func indent(s string) string {
	lines := strings.Split(strings.TrimRight(s, "\n"), "\n")
	for i, l := range lines {
		lines[i] = "    " + l
	}
	return strings.Join(lines, "\n") + "\n"
}
